/**
 * 이미지 키에서 단어 id 부분만 추출한다.
 * 예: '10_本_책' -> '10',  'n4_154_移る_이동하다' -> 'n4_154'
 * (seedWords의 imageKey는 중간에 카테고리 세그먼트가 끼어 있어 wordImages 키와
 *  직접 매칭되지 않으므로, 양쪽에 공통인 id 부분으로 색인한다.)
 */
function extractWordId(key: string): string {
  return key.startsWith('n4_')
    ? key.split('_').slice(0, 2).join('_') // 'n4_154'
    : key.split('_')[0]; // '10'
}

// 앱 로드 시 1회만 id -> 이미지 색인을 만든다.
const imagesById: Record<string, any> = {};
for (const key in wordImages) {
  imagesById[extractWordId(key)] = wordImages[key];
}

/**
 * 단어(word.id 기준)에 해당하는 이미지 모듈을 반환한다. 없으면 undefined.
 * word는 { id, imageKey? } 형태면 충분하다.
 */
export function getWordImage(word: { id: string; imageKey?: string }): any {
  return imagesById[word.id];
}
